import type { EvidenceDossier, VariantCase } from '../../types/variant'

function pct(value: number) {
  return `${(value * 100).toFixed(value < 0.001 ? 4 : 3)}%`
}

export function generateMarkdownReport(variantCase: VariantCase, dossier: EvidenceDossier) {
  return [
    '# VariantVision Pro Evidence Dossier',
    '',
    `Generated: ${dossier.generatedAt}`,
    `Case: ${dossier.isCuratedCase ? variantCase.title : 'Custom input (curated case evidence detached)'}`,
    `Gene: ${dossier.input.gene}`,
    `Variant: ${dossier.input.variant}`,
    `Build: ${dossier.input.build}`,
    `Normalized ID: ${dossier.normalized.vcfId ?? 'manual review required'}`,
    `VCF-like coordinate: ${dossier.normalized.vcfLikeCoordinate ?? 'manual review required'}`,
    '',
    '## Evidence Coverage',
    '',
    `Score: ${dossier.coverageScore}/100`,
    `Band: ${dossier.coverageBand}`,
    dossier.coverageMethodology,
    '',
    ...dossier.metrics.map((metric) => `- ${metric.label}: ${metric.score}/100 (${metric.status}) - ${metric.explanation}`),
    '',
    '## Amino Acid Comparison',
    '',
    `Original: ${dossier.aminoAcid.original.name} (${dossier.aminoAcid.original.code})`,
    `Replacement: ${dossier.aminoAcid.replacement.name} (${dossier.aminoAcid.replacement.code})`,
    `Charge: ${dossier.aminoAcid.chargeShift}`,
    `Polarity: ${dossier.aminoAcid.polarityShift}`,
    `Hydropathy delta: ${dossier.aminoAcid.hydropathyDelta}`,
    `Interpretation: ${dossier.aminoAcid.interpretation}`,
    '',
    '## Population Summary',
    '',
    'Fixture cohorts are shown separately; overlapping or differently sampled cohorts are not pooled.',
    `Highest row frequency: ${dossier.populationSummary.highestFrequency === null ? 'Unavailable' : pct(dossier.populationSummary.highestFrequency)}`,
    `Highest fixture group: ${dossier.populationSummary.highestGroup ?? 'Unavailable'}`,
    ...dossier.populationRecords.map((row) => `- ${row.group.toUpperCase()} ${row.source}: AC ${row.alleleCount}, AN ${row.alleleNumber}, AF ${pct(row.alleleCount / row.alleleNumber)}, homozygotes ${row.homozygotes}`),
    '',
    '## Source Records',
    '',
    ...dossier.sourceRecords.flatMap((record) => [
      `- ${record.kind}: ${record.label} [${record.status}; ${record.weight}] - ${record.detail}`,
      `  Source: ${record.source}. Origin: ${record.isLive ? 'live retrieval' : 'local parser or teaching fixture'}. Reviewed: ${record.lastReviewed}.`,
      ...(record.url ? [`  URL: ${record.url}`] : []),
      ...(record.retrievedAt ? [`  Retrieved: ${record.retrievedAt}. Retrieval status: ${record.retrievalStatus ?? 'unspecified'}.`] : []),
    ]),
    '',
    '## Live Retrieval Log',
    '',
    ...(dossier.liveProviderHealth?.length ? dossier.liveProviderHealth.flatMap((provider) => [
      `- ${provider.provider}: ${provider.status}, ${provider.durationMs}ms, ${provider.retrievedAt}. Query/ID: ${provider.variantIdUsed ?? 'unspecified'}.`,
      ...(provider.sourceUrl ? [`  Source URL: ${provider.sourceUrl}`] : []),
      ...(provider.error ? [`  Error: ${provider.error}`] : []),
      ...(provider.warnings ?? []).map((warning) => `  Warning: ${warning}`),
    ]) : ['No live retrieval has been performed for this input.']),
    '',
    '## Literature Leads',
    '',
    ...dossier.literature.map((item) => `- ${item.title}. ${item.journal}, ${item.year ?? 'year unavailable'}. ${item.url} [${item.origin ?? 'curated literature lead'}; ${item.retrievedAt ? `retrieved ${item.retrievedAt}` : `metadata verified ${item.metadataVerifiedAt ?? 'date unavailable'}`}]`),
    '',
    '## Boundary',
    '',
    dossier.responsibleBoundary,
    '',
    '## Fixture Note',
    '',
    'This MVP uses curated demo fixtures and source leads for portfolio review. It is designed to show architecture, evidence workflow, and responsible UX. Refresh public databases manually before using any record for real research decisions.',
    '',
    '## Disclaimer',
    '',
    'Coverage reflects available evidence streams, not pathogenicity, clinical confidence, or diagnostic certainty. This tool is for research purposes only and not intended for clinical use.',
  ].join('\n')
}
